#!/usr/bin/env node
/* eslint-disable no-console */
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'serverless.yml');
const outputPath = path.join(repoRoot, 'serverless.deployable.yml');

if (!fs.existsSync(sourcePath)) {
  console.error('serverless.yml not found');
  process.exit(1);
}

const source = fs.readFileSync(sourcePath, 'utf8');
const lines = source.split(/\r?\n/);

const functionsStart = lines.findIndex(line => /^functions:\s*$/.test(line));
if (functionsStart === -1) {
  console.error('functions section not found in serverless.yml');
  process.exit(1);
}

const sectionEnd = (() => {
  for (let i = functionsStart + 1; i < lines.length; i += 1) {
    if (/^[^\s#][^:]*:\s*$/.test(lines[i])) return i;
  }
  return lines.length;
})();

function handlerExists(handlerRef) {
  if (!handlerRef) return true;
  const [modulePath] = handlerRef.split('.');
  const tsPath = path.join(repoRoot, `${modulePath}.ts`);
  const jsPath = path.join(repoRoot, `${modulePath}.js`);
  return fs.existsSync(tsPath) || fs.existsSync(jsPath);
}

const header = lines.slice(0, functionsStart + 1);
const footer = lines.slice(sectionEnd);
const body = lines.slice(functionsStart + 1, sectionEnd);

const outBody = [];
const pruned = [];
let totalFunctions = 0;
let deployableFunctions = 0;

let i = 0;
while (i < body.length) {
  if (/^  [A-Za-z0-9_-]+:\s*$/.test(body[i])) {
    const fnName = body[i].trim().slice(0, -1);
    const block = [body[i]];
    i += 1;
    while (i < body.length && !/^  [A-Za-z0-9_-]+:\s*$/.test(body[i])) {
      block.push(body[i]);
      i += 1;
    }

    totalFunctions += 1;
    const handlerLine = block.find(line => /^\s{4}handler:\s*[^\s#]+/.test(line));
    const handlerRef = handlerLine ? handlerLine.trim().replace(/^handler:\s*/, '') : null;
    if (handlerExists(handlerRef)) {
      deployableFunctions += 1;
      outBody.push(...block);
    } else {
      pruned.push({ function: fnName, handler: handlerRef });
      while (outBody.length > 0 && /^\s*$/.test(outBody[outBody.length - 1])) {
        outBody.pop();
      }
    }
  } else {
    outBody.push(body[i]);
    i += 1;
  }
}

const banner = [
  '# AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.',
  '# Generated by scripts/generate-deployable-serverless.js',
  '# Source: serverless.yml',
  '',
].join('\n');

const generated = [...header, ...outBody, ...footer].join('\n');
fs.writeFileSync(outputPath, `${banner}${generated.trimEnd()}\n`);

console.log(
  JSON.stringify(
    {
      source: 'serverless.yml',
      output: 'serverless.deployable.yml',
      totalFunctions,
      deployableFunctions,
      prunedFunctions: pruned.length,
      samplePruned: pruned.slice(0, 20),
    },
    null,
    2
  )
);
